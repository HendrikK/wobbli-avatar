// Builds src/generated/ from data/: the state metadata every avatar needs, one module per state group
// (parts and CSS, loaded on first use) and one per holiday region (costume parts and CSS, loaded when a
// holiday is set). Runs before tests, type checks and the package build.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const DATA = path.join(ROOT, 'data');
const OUT = path.join(ROOT, 'src/generated');
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const read = p => fs.readFileSync(path.join(DATA, p), 'utf8');
const json = p => JSON.parse(read(p));
const css = p => read(p).replace(/\/\*[\s\S]*?\*\//g, '').split('\n').map(l => l.trim()).filter(Boolean).join('\n');
const HEADER = '// Generated by scripts/build-data.mjs from data/. Do not edit.\n';
const write = (name, body) => fs.writeFileSync(path.join(OUT, name), HEADER + body);
const lit = v => JSON.stringify(v);

const events = json('events.json');
const states = events.states.map(k => json('states/' + k + '.json'));
const GROUPS = ['chat', 'feelings', 'data', 'work', 'talk', 'status'];
const GROUP_NAMES = { chat: 'In the chat', feelings: 'Feelings', data: 'Moving data', work: 'Working', talk: 'Waiting and talking', status: 'System status' };

// ---------- state metadata (always loaded) ----------
const meta = states.map(({ parts, ...s }) => s);
write('meta.ts',
  "import type { StateMeta, EventsData } from '../types.js';\n" +
  'export const STATES: StateMeta[] = ' + lit(meta) + ';\n' +
  'export const GROUPS = ' + lit(GROUPS) + ' as const;\n' +
  'export const GROUP_NAMES: Record<string, string> = ' + lit(GROUP_NAMES) + ';\n' +
  'export const EVENTS_DATA: EventsData = ' + lit({ ...events, states: undefined }) + ';\n');

// ---------- one module per state group ----------
const byGroup = {};
states.forEach(s => { (byGroup[s.group] = byGroup[s.group] || []).push(s); });
GROUPS.forEach(g => {
  const list = byGroup[g] || [];
  const parts = [];
  const seen = new Set();
  list.forEach(s => s.parts.forEach(p => { const id = p.zone + ':' + p.k; if (!seen.has(id)) { seen.add(id); parts.push([p.zone, p.i, p.k, p.on, p.t]); } }));
  write('group-' + g + '.ts',
    "import type { PartsPack } from '../types.js';\n" +
    'const pack: PartsPack = { id: ' + lit('group:' + g) + ', states: ' + lit(list.map(s => s.key)) + ', parts: ' + lit(parts) + ', css: ' + lit(list.map(s => css('states/' + s.key + '.css')).join('\n')) + ' };\nexport default pack;\n');
});
write('base-css.ts', 'export const BASE_CSS = ' + lit(css('runtime.css') + '\n' + css('base.css')) + ';\n');

// ---------- holidays ----------
// in the prototype's order: the shared holidays, then the regions as they were added
const PACK_ORDER = ['shared', 'us', 'ie', 'in', 'gb', 'mx', 'jp', 'cn', 'br', 'de', 'kr', 'se', 'ca', 'au', 'fr'];
const rank = p => (PACK_ORDER.includes(p) ? PACK_ORDER.indexOf(p) : PACK_ORDER.length);
const packs = fs.readdirSync(path.join(DATA, 'holidays')).filter(f => f.endsWith('.json')).map(f => json('holidays/' + f)).sort((a, b) => rank(a.pack) - rank(b.pack));
const holMeta = [];
const regions = {};
let sharedRules = null;
packs.forEach(p => {
  p.holidays.forEach(h => holMeta.push({ ...h, pack: p.pack }));
  if (p.pack === 'shared') sharedRules = p.rules;
  else regions[p.region] = { name: p.name, pack: p.pack, shared: p.shared, overrides: p.overrides || {}, dates: p.dates, moon: p.moon || {} };
});
// the packs that hold a holiday's costume parts: its own, plus the owner of any costume it shares
// (Dia dos Namorados wears the Valentine's costumes, which live in the shared pack)
const COS_PACKS = {};
packs.forEach(p => p.parts.forEach(x => x.on.forEach(t => { if (t.startsWith('cos-')) (COS_PACKS[t.slice(4)] = COS_PACKS[t.slice(4)] || new Set()).add(p.pack); })));
holMeta.forEach(h => { h.packs = [...new Set([h.pack, ...h.costumes.flatMap(c => [...(COS_PACKS[c.key] || [])])])]; });
const PACK_OF = {}; holMeta.forEach(h => { PACK_OF[h.key] = h.pack; });
// a region loads its own pack, the shared one and the packs of the holidays it borrows (Easter Monday, Boxing Day)
Object.values(regions).forEach(r => {
  const keys = new Set([...r.shared, ...r.dates.map(d => d.key)]);
  r.packs = [...new Set([...keys].flatMap(k => holMeta.find(h => h.key === k).packs))];
});
write('holiday-meta.ts',
  "import type { HolidayMeta, RegionData, DateSpec } from '../holidays/types.js';\n" +
  'export const HOLIDAYS: HolidayMeta[] = ' + lit(holMeta) + ';\n' +
  'export const SHARED_RULES: Record<string, DateSpec> = ' + lit(sharedRules) + ';\n' +
  'export const REGIONS: Record<string, RegionData> = ' + lit(regions) + ';\n');
packs.forEach(p => {
  const parts = p.parts.map(x => [x.zone, x.i, x.k, x.on, x.t]);
  write('hol-' + p.pack + '.ts',
    "import type { PartsPack } from '../types.js';\n" +
    'const pack: PartsPack = { id: ' + lit('holidays:' + p.pack) + ', states: [], parts: ' + lit(parts) + ', css: ' + lit(css('holidays/' + p.pack + '.css')) + ' };\nexport default pack;\n');
});
write('hol-common.ts', 'export const HOLIDAY_CSS = ' + lit(css('holidays/common.css')) + ';\n');
const loaders = packs.map(p => '  ' + lit(p.pack) + ": () => import('./hol-" + p.pack + ".js').then(m => m.default)").join(',\n');
write('hol-loaders.ts', "import type { PartsPack } from '../types.js';\nexport const PACK_LOADERS: Record<string, () => Promise<PartsPack>> = {\n" + loaders + '\n};\n');

console.log('generated', states.length, 'states in', GROUPS.length, 'groups and', packs.length, 'holiday packs');
